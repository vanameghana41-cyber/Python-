
square = lambda x: x**2
print("Square of 5:", square(5))
is_even = lambda x: x % 2 == 0
print("Is 4 even?", is_even(4))
print("Is 7 even?", is_even(7))
larger = lambda a, b: a if a > b else b
print("Larger of 10 and 25:", larger(10, 25))
'''Square of 5: 25
Is 4 even? True
Is 7 even? False
Larger of 10 and 25: 25'''
